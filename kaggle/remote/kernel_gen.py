def collect_results(env_report: dict, eval_info: dict, trees: dict) -> dict:
    records = []
    summary = None
    source_dirs = [RESULTS]
    if JOB.get("tasks"):
        source_dirs = [RESULTS / "records"]
    for source in source_dirs:
        if not source.exists():
            continue
        for path in sorted(source.glob("*.json")):
            if path.name == "summary.json":
                continue
            try:
                record = json.loads(path.read_text())
            except json.JSONDecodeError:
                log(f"skipping unreadable result {path}")
                continue
            # evalrun writes the record file before attaching record_path, so
            # the tuner's job name has to come from the file name.
            record.setdefault("record_name", path.name)
            records.append(record)
    summary_path = RESULTS / "summary.json"
    if summary_path.exists():
        summary = json.loads(summary_path.read_text())
    tasks_status = None
    status_path = WORK / "tasks_status.json"
    if status_path.exists():
        tasks_status = json.loads(status_path.read_text())
    gate = None
    gate_path = WORK / "gate.json"
    if gate_path.exists():
        gate = json.loads(gate_path.read_text())
    shard = {
        "job": JOB,
        "tasks_status": tasks_status,
        "gate": gate,
        "env": {**env_report, "tree_timings": trees, "total_seconds": round(time.time() - T0, 1)},
        "eval": eval_info,
        "records": records,
        "summary": summary,
    }
    (WORK / "shard.json").write_text(json.dumps(shard, indent=1))
    (WORK / "env.json").write_text(json.dumps(shard["env"], indent=1))
    log(f"shard.json written: {len(records)} records, exit={eval_info['returncode']}")
    return shard


