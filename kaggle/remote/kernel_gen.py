def _ignore(_directory, names):
    return [name for name in names if name == "__pycache__"]


def payload_pool_root() -> Path:
    """Where the generated pool scenarios live (expanded dir or inside the zip).

    Kaggle expands uploaded archives, so on the mount the pool usually arrives
    as ``pool/scenarios/``; a local rehearsal keeps the zip. The source root is
    whatever ``find_payload_source`` resolved, not the documented path.
    """
    sources = [PAYLOAD] + ([PAYLOAD_SOURCE] if PAYLOAD_SOURCE else []) + [DATASET_DIR]
    for base in sources:
        if (base / "pool" / "scenarios").is_dir():
            return base / "pool" / "scenarios"
    for base in sources:
        zip_path = base / "pool" / "scenarios.zip"
        if zip_path.exists():
            target = PAYLOAD / "pool" / "scenarios"
            with zipfile.ZipFile(zip_path) as archive:
                archive.extractall(target)
            return target
    raise RuntimeError(
        "payload has neither pool/scenarios/ nor pool/scenarios.zip under "
        + ", ".join(str(base) for base in sources)
    )


def _link_or_copy(source: Path, destination: Path) -> None:
    """Hard link, else symlink, else copy: the mount is read-only and slow."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.is_symlink() or destination.exists():
        return
    for attempt in ("hardlink", "symlink", "copy"):
        try:
            if attempt == "hardlink":
                os.link(source, destination)
            elif attempt == "symlink":
                os.symlink(source, destination)
            else:
                shutil.copy2(source, destination)
            return
        except OSError:
            continue
    raise RuntimeError(f"cannot materialise {destination} from {source}")


def build_trees(info: dict) -> dict:
    source = MOUNT / "smart_buildings"
    if not (source / "__init__.py").exists():
        raise RuntimeError(f"competition mount has no simulator at {source}")
    sims = PAYLOAD / "sims"
    shipped = sims / "shipped"
    corrected = sims / "corrected"
    timings = {}

    started = time.time()
    if not (shipped / "smart_buildings" / "__init__.py").exists():
        shutil.copytree(
            source, shipped / "smart_buildings", ignore=_ignore, dirs_exist_ok=True
        )
    timings["shipped_copy_seconds"] = round(time.time() - started, 1)
    log(f"sims/shipped built from the mount in {timings['shipped_copy_seconds']}s")

    started = time.time()
    if not (corrected / "smart_buildings" / "__init__.py").exists():
        shutil.copytree(
            shipped / "smart_buildings",
            corrected / "smart_buildings",
            ignore=_ignore,
            dirs_exist_ok=True,
        )
        sys.path.insert(0, str(PAYLOAD / "tools"))
        import patch_apply  # noqa: PLC0415

        patch_names = sorted(Path(name).name for name in info["patches"])
        texts = [(PAYLOAD / "patches" / name).read_text() for name in patch_names]
        for line in patch_apply.apply_patches(corrected, texts):
            log("patch: " + line)
    timings["corrected_build_seconds"] = round(time.time() - started, 1)

    # The mount is the competition's own snapshot, which can lag or lead our
    # pinned tree in *unpatched* lines (comments, unrelated fixes). What must
    # hold is: every patch hunk applied (the applier is strict about context),
    # and files the patch creates are byte-identical to ours. Patched existing
    # files are compared and the drift is reported rather than fatal.
    verified, drifted, created_mismatch = [], [], []
    for rel, digest in info["post_patch_sha"].items():
        path = corrected / rel
        ok = path.exists() and sha256_file(path) == digest
        if ok:
            verified.append(rel)
            continue
        drifted.append(rel)
        if not info["pre_patch_sha"].get(rel):
            created_mismatch.append(rel)
    if created_mismatch:
        raise RuntimeError(
            f"patch-created files differ from sims/corrected: {created_mismatch}"
        )
    log(
        f"sims/corrected: {len(verified)} patched files byte-identical to sims/corrected, "
        f"{len(drifted)} differ outside the patched hunks: {drifted}"
    )
    pre_drifted = [
        rel
        for rel, digest in info["pre_patch_sha"].items()
        if digest and sha256_file(shipped / rel) != digest
    ]

    started = time.time()
    for tree in (shipped, corrected):
        scenarios = tree / "smart_buildings" / "training_scenarios"
        marker = scenarios / ".pool_extracted"
        if not marker.exists():
            pool_root = payload_pool_root()
            for path in sorted(pool_root.rglob("*")):
                if path.is_file():
                    _link_or_copy(path, scenarios / path.relative_to(pool_root))
            marker.write_text(info["hash"])
        weather = tree / "smart_buildings" / "weather"
        (weather / "csv").mkdir(parents=True, exist_ok=True)
        for preset in sorted((PAYLOAD / "weather").glob("*.yaml")):
            _link_or_copy(preset, weather / preset.name)
        for csv in sorted((PAYLOAD / "weather" / "csv").glob("*.csv")):
            _link_or_copy(csv, weather / "csv" / csv.name)
    timings["pool_and_weather_seconds"] = round(time.time() - started, 1)

    # The pool .zip itself cannot be byte-hashed (Kaggle repacks archives on
    # upload), so verify what came out of it, in the tree the job will use.
    scenarios = PAYLOAD / "sims" / JOB["sim"] / "smart_buildings" / "training_scenarios"
    bad_pool, size_checked, digest_checked = [], 0, 0
    for rel, digest in info["pool_files"].items():
        path = scenarios / rel
        size = info.get("pool_sizes", {}).get(rel)
        if not path.exists():
            bad_pool.append(rel)
            continue
        if size is not None and path.stat().st_size != size:
            bad_pool.append(rel)
            continue
        size_checked += 1
        # Hashing the 3 MB .npy grids through the mount costs ~1 minute; the
        # config files carry the scenario identity, so hash those and size-check
        # the arrays (a truncated or swapped dataset still trips this).
        if size is None or size <= 65536:
            if sha256_file(path) != digest:
                bad_pool.append(rel)
                continue
            digest_checked += 1
    if bad_pool:
        raise RuntimeError(f"pool scenarios failed verification: {bad_pool[:10]}")
    log(
        f"pool scenarios verified: {len(info['pool_files'])} files "
        f"({digest_checked} by digest, {size_checked - digest_checked} by size)"
    )

    missing = [
        scenario
        for scenario in JOB["scenarios"]
        if not (
            PAYLOAD
            / "sims"
            / JOB["sim"]
            / "smart_buildings"
            / "training_scenarios"
            / scenario
            / "config.gin"
        ).exists()
    ]
    if missing:
        raise RuntimeError(f"scenarios missing from the {JOB['sim']} tree: {missing}")
    timings["corrected_post_verified"] = verified
    timings["corrected_post_drifted"] = drifted
    timings["shipped_pre_patch_drifted"] = pre_drifted
    return timings


def compare_mount_to_local(info: dict) -> dict:
    """Does the mounted simulator code still match our local ``sims/shipped``?"""
    reference = info.get("shipped_code_sha") or {}
    root = MOUNT / "smart_buildings"
    differing = []
    for rel, digest in reference.items():
        path = root / rel[len("smart_buildings/") :] if rel.startswith("smart_buildings/") else root / rel
        if not path.exists() or sha256_file(path) != digest:
            differing.append(rel)
    seen = {
        "smart_buildings/" + p.relative_to(root).as_posix()
        for p in root.rglob("*.py")
        if "__pycache__" not in p.as_posix()
    }
    extra = sorted(seen - set(reference))
    result = {
        "reference_files": len(reference),
        "differing": differing,
        "extra": extra,
        "match": not differing and not extra,
    }
    log(
        f"mount vs local sims/shipped: {result['reference_files']} files, "
        f"{len(differing)} differ, {len(extra)} extra -> match={result['match']}"
    )
    return result


