def run_eval() -> dict:
    command = [
        sys.executable,
        "-m",
        "sbx.evalrun",
        "--policy",
        JOB["policy"],
        "--steps",
        str(JOB["steps"]),
        "--sim",
        JOB["sim"],
        "--workers",
        str(JOB["workers"]),
        "--tag",
        JOB["tag"],
        "--out",
        str(RESULTS),
        "--components",
        JOB["components"],
        "--start-offset-days",
        str(JOB["start_offset_days"]),
    ]
    # One --scenario flag: argparse's nargs="+" keeps only the last occurrence.
    command += ["--scenario", *JOB["scenarios"]]
    if JOB.get("params"):
        command += ["--params", json.dumps(JOB["params"])]
    if JOB.get("cenv"):
        command += ["--cenv", str(JOB["cenv"])]
    if JOB.get("fast"):
        command += ["--fast"]
    if JOB.get("occupancy_seed") is not None:
        command += ["--occupancy-seed", str(JOB["occupancy_seed"])]
    if JOB.get("oracle"):
        command += ["--oracle", ",".join(JOB["oracle"])]
        if JOB.get("oracle_horizon"):
            command += ["--oracle-horizon", str(JOB["oracle_horizon"])]

    env = dict(os.environ)
    env["PYTHONPATH"] = str(PAYLOAD) + (
        os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else ""
    )
    env["PYTHONUNBUFFERED"] = "1"
    log("exec " + " ".join(command))
    started = time.time()
    proc = subprocess.run(
        command, cwd=str(PAYLOAD), env=env, text=True, capture_output=True
    )
    wall = time.time() - started
    (WORK / "eval.log").write_text(
        "COMMAND: " + " ".join(command) + "\\n\\nSTDOUT\\n" + proc.stdout + "\\nSTDERR\\n" + proc.stderr
    )
    tail = proc.stdout.strip().splitlines()[-25:]
    for line in tail:
        print(line, flush=True)
    if proc.returncode != 0:
        log("evalrun stderr tail:")
        for line in proc.stderr.strip().splitlines()[-40:]:
            print(line, flush=True)
    log(f"evalrun exit={proc.returncode} wall={wall:.1f}s")
    return {"returncode": proc.returncode, "wall_seconds": round(wall, 2)}


def run_tasks() -> dict:
    """Mode ``tasks``: the tuner's (candidate, scenario) jobs, one shard.

    The task list is the tuner's, untouched: each task carries its own
    ``params`` dict, and ``sbx.evalrun._worker`` applies it exactly like the
    local path (``PolicyCls.PARAMS`` overridden for the rest of that process).
    """
    out_dir = RESULTS / "records"
    spec = {
        "tasks": JOB["tasks"],
        "out_dir": str(out_dir),
        "workers": JOB["workers"],
        "job_timeout": JOB.get("job_timeout", 1800),
    }
    spec_path = WORK / "tasks.json"
    spec_path.write_text(json.dumps(spec))
    status_path = WORK / "tasks_status.json"
    runner = PAYLOAD / "tools" / "remote_tasks.py"
    command = [
        sys.executable,
        str(runner),
        "--tasks",
        str(spec_path),
        "--status",
        str(status_path),
    ]
    env = dict(os.environ)
    env["PYTHONPATH"] = str(PAYLOAD) + (
        os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else ""
    )
    env["PYTHONUNBUFFERED"] = "1"
    log(f"exec {len(JOB['tasks'])} tasks with {JOB['workers']} workers")
    started = time.time()
    proc = subprocess.run(command, cwd=str(PAYLOAD), env=env, text=True, capture_output=True)
    wall = time.time() - started
    (WORK / "eval.log").write_text(
        "COMMAND: " + " ".join(command) + "\\n\\nSTDOUT\\n" + proc.stdout + "\\nSTDERR\\n" + proc.stderr
    )
    for line in proc.stdout.strip().splitlines()[-10:]:
        print(line, flush=True)
    if proc.returncode != 0:
        for line in proc.stderr.strip().splitlines()[-20:]:
            print(line, flush=True)
    return {"returncode": proc.returncode, "wall_seconds": round(wall, 2)}


def run_gate() -> dict:
    """Mode ``gate``: plain Python vs ``--cenv`` through ``cenv/verify/gate.py``.

    For every (sim tree, scenario) pair the kernel runs two episodes in
    independent processes -- one pure Python, one with the C components
    installed -- and then compares the two traces with the same tool we use
    locally: ``python -m cenv.verify.gate compare``. Nothing here re-implements
    the comparison.
    """
    spec = JOB["gate"]
    out_dir = WORK / "gate"
    out_dir.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env["PYTHONPATH"] = str(PAYLOAD) + (
        os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else ""
    )
    env["PYTHONUNBUFFERED"] = "1"
    results = []
    for sim in spec["sims"]:
        for scenario in spec["scenarios"]:
            stem = f"{sim}__{scenario.replace('/', '__')}"
            paths = {
                side: out_dir / f"{stem}__{side}.npz"
                for side in ("plain", "cenv")
            }
            for side, cenv_spec in (("plain", None), ("cenv", spec["cenv"])):
                command = [
                    sys.executable,
                    "-m",
                    "cenv.verify.gate",
                    "trace",
                    "--scenario",
                    scenario,
                    "--steps",
                    str(spec["steps"]),
                    "--policy",
                    spec["policy"],
                    "--sim",
                    sim,
                    "--out",
                    str(paths[side]),
                    "--components",
                    JOB["components"],
                ]
                if spec.get("params"):
                    command += ["--params", json.dumps(spec["params"])]
                if cenv_spec:
                    command += ["--cenv", cenv_spec]
                log(f"gate trace {side}: {scenario} {sim} {spec['steps']} steps")
                started = time.time()
                proc = subprocess.run(
                    command, cwd=str(PAYLOAD), env=env, text=True, capture_output=True
                )
                with open(WORK / "eval.log", "a") as handle:
                    handle.write(
                        "COMMAND: " + " ".join(command) + "\\n"
                        + proc.stdout + "\\n" + proc.stderr + "\\n"
                    )
                for line in proc.stdout.strip().splitlines()[-3:]:
                    print(line, flush=True)
                if proc.returncode != 0:
                    raise RuntimeError(
                        f"gate trace {side} failed for {scenario} ({sim}):\\n"
                        + proc.stderr[-4000:]
                    )
                log(f"gate trace {side}: {scenario} {sim} done in {time.time() - started:.0f}s")

            # ``gate compare`` takes an *absolute* temperature tolerance. The
            # acceptance criterion is relative (<= temp_rel_tol of the trace's
            # own temperature scale), so scale it by the largest |T| the plain
            # trace reached. Reading the npz for that scale is the only thing
            # this wrapper computes; the comparison itself stays in gate.py.
            import numpy as np

            with np.load(paths["plain"], allow_pickle=True) as trace_npz:
                zone_temps = trace_npz["zone_temps"]
            temp_scale = float(np.abs(zone_temps).max()) if zone_temps.size else 0.0
            temp_tol_abs = spec["temp_rel_tol"] * temp_scale

            json_out = out_dir / f"{stem}__compare.json"
            command = [
                sys.executable,
                "-m",
                "cenv.verify.gate",
                "compare",
                str(paths["plain"]),
                str(paths["cenv"]),
                "--rel-tol",
                str(spec["rel_tol"]),
                "--temp-tol",
                repr(temp_tol_abs),
                "--json",
                str(json_out),
            ]
            proc = subprocess.run(
                command, cwd=str(PAYLOAD), env=env, text=True, capture_output=True
            )
            print(proc.stdout, flush=True)
            if proc.returncode not in (0, 1) or not json_out.exists():
                raise RuntimeError(
                    f"gate compare failed for {scenario} ({sim}):\\n" + proc.stderr[-4000:]
                )
            comparison = json.loads(json_out.read_text())
            comparison["sim"] = sim
            comparison["scenario"] = scenario
            comparison["steps_requested"] = spec["steps"]
            comparison["temp_scale_K"] = temp_scale
            comparison["temp_tol_abs_K"] = temp_tol_abs
            comparison["max_zone_temp_rel"] = (
                comparison["max_zone_temp_abs_K"] / temp_scale
                if comparison["max_zone_temp_abs_K"] is not None and temp_scale
                else None
            )
            results.append(comparison)
    summary = {
        "spec": spec,
        "results": results,
        "passed": all(item["passed"] for item in results),
        "max_total_reward_rel_diff": max(
            (item["total_reward_rel_diff"] for item in results), default=0.0
        ),
        "max_zone_temp_abs_K": max(
            (item["max_zone_temp_abs_K"] or 0.0 for item in results), default=0.0
        ),
        "max_zone_temp_rel": max(
            (item["max_zone_temp_rel"] or 0.0 for item in results), default=0.0
        ),
    }
    (WORK / "gate.json").write_text(json.dumps(summary, indent=1))
    log(
        f"gate {'PASS' if summary['passed'] else 'FAIL'}: "
        f"{len(results)} comparison(s), max total rel diff "
        f"{summary['max_total_reward_rel_diff']:.3e}, max |dT| "
        f"{summary['max_zone_temp_abs_K']:.3e} K "
        f"({summary['max_zone_temp_rel']:.3e} relative)"
    )
    return summary


