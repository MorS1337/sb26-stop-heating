"""Generates one self-contained Kaggle script kernel per job shard.

The generated ``run.py`` is a thin launcher: it unzips the payload dataset,
rebuilds ``sims/shipped`` from the competition mount and ``sims/corrected`` from
that copy plus the frozen patches, verifies every hash, then calls
``python -m sbx.evalrun`` as a *subprocess*.

Why a subprocess and not ``sbx.evalrun.run(...)`` inline: Kaggle runs script
kernels through nbconvert (``__script__.ipynb``), so ``__main__`` has no usable
``__file__`` for ``multiprocessing``'s spawn start method. Launching the module
gives the workers a normal script to re-import, and keeps the wall-clock of the
evaluation separate from the setup timing.

The job spec is embedded as the ``JOB`` dict at the top of the file, so a pushed
kernel says exactly what it ran (policy, params, scenarios, steps, sim,
start offset, components, payload hash, and whether the C step was on).

Two optional modes ride on the same launcher:

* ``JOB["cenv"]``/``JOB["fast"]`` -- compile ``payload/cenv`` with the kernel's
  own toolchain (loudly: a failed build aborts the shard) and add
  ``--cenv <spec> --fast`` to the ``sbx.evalrun`` command. Absent = the plain
  Python path, unchanged.
* ``JOB["gate"]`` -- no evaluation: run ``cenv/verify/gate.py`` trace twice per
  (sim tree, scenario) -- pure Python and ``--cenv`` -- and compare the traces
  with the same module's ``compare``. Writes ``gate.json``.

Outputs written to ``/kaggle/working``:

* ``results/<tag>/*.json`` -- exactly what the local runner writes;
* ``shard.json`` -- job, records, summary, env (downloaded and merged by the
  driver; also survives any output-path surprise);
* ``env.json`` -- timing and version probe;
* ``eval.log`` -- stdout/stderr of the evaluation subprocess.
"""

