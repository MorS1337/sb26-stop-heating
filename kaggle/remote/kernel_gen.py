def _dataset_roots() -> list[Path]:
    """Where a dataset can appear: the documented path and the newer layouts."""
    slug = DATASET_DIR.name
    roots = [
        DATASET_DIR,
        Path("/kaggle/input/datasets/mors1337") / slug,
        Path("/kaggle/input/datasets") / slug,
        Path("/kaggle/input") / slug,
    ]
    unique: list[Path] = []
    for root in roots:
        if root not in unique:
            unique.append(root)
    return unique


def find_payload_source() -> tuple[str, Path]:
    for base in _dataset_roots():
        if (base / "payload_info.json").exists():
            return "dir", base
        zips = sorted(base.glob("*.zip")) if base.is_dir() else []
        if zips:
            return "zip", zips[0]
    # Last resort: a bounded search of /kaggle/input (layout changes over time).
    inputs_root = Path("/kaggle/input")
    if inputs_root.is_dir():
        for pattern in ("*/*/payload_info.json", "*/payload_info.json", "*/*/*/payload_info.json"):
            for info in sorted(inputs_root.glob(pattern)):
                return "dir", info.parent
    inputs = sorted(str(p) for p in inputs_root.iterdir()) if inputs_root.is_dir() else []
    listing = []
    for name in inputs:
        sub = Path(name)
        listing.append((name, sorted(str(p) for p in sub.iterdir())[:6] if sub.is_dir() else []))
    raise RuntimeError(
        f"payload dataset not mounted under any of {[str(p) for p in _dataset_roots()]}; "
        f"/kaggle/input holds {listing}"
    )


def materialise_payload() -> None:
    if (PAYLOAD / "payload_info.json").exists():
        log(f"payload already materialised at {PAYLOAD}")
        return
    kind, source = find_payload_source()
    global PAYLOAD_SOURCE
    PAYLOAD_SOURCE = source
    log(f"payload source: {kind} {source}")
    if kind == "dir":
        # Skip pool/scenarios: Kaggle expands the uploaded archive into that
        # directory, and it is read straight off the mount instead of being
        # duplicated (456 MB) here.
        shutil.copytree(source, PAYLOAD, ignore=shutil.ignore_patterns("scenarios"))
        return
    staging = WORK / "payload_extract"
    shutil.rmtree(staging, ignore_errors=True)
    with zipfile.ZipFile(source) as archive:
        archive.extractall(staging)
    if not (staging / "payload_info.json").exists():
        candidates = [p.parent for p in staging.rglob("payload_info.json")]
        if not candidates:
            raise RuntimeError(f"{source} has no payload_info.json inside")
        staging = candidates[0]
    shutil.move(str(staging), str(PAYLOAD))
    shutil.rmtree(WORK / "payload_extract", ignore_errors=True)


def verify_payload() -> dict:
    info = json.loads((PAYLOAD / "payload_info.json").read_text())
    if info["hash"] != JOB["payload_hash"]:
        raise RuntimeError(
            f"payload hash {info['hash']} != job's {JOB['payload_hash']}; "
            "the dataset version is stale -- re-push it (python -m kaggle.remote.payload)"
        )
    bad = [
        rel
        for rel, digest in info["files"].items()
        if not (PAYLOAD / rel).exists() or sha256_file(PAYLOAD / rel) != digest
    ]
    if bad:
        raise RuntimeError(f"payload files failed digest check: {bad[:10]}")
    log(f"payload verified: {len(info['files'])} files, hash {info['hash']}")
    return info


