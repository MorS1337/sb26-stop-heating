def build_cenv() -> dict:
    """Compiles ``payload/cenv`` with the kernel's own toolchain, loudly.

    ``cenv/build.py`` pins the flags (``-O3 -ffp-contract=off -fno-fast-math``)
    and stamps the build, so the worker processes reuse this library instead of
    recompiling. A failure raises: a shard must never quietly run plain Python
    when the job asked for the C step.
    """
    if str(PAYLOAD) not in sys.path:
        sys.path.insert(0, str(PAYLOAD))
    import cenv.build as cenv_build  # noqa: PLC0415

    env = dict(os.environ)
    env["PYTHONPATH"] = str(PAYLOAD) + (
        os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else ""
    )
    env["PYTHONUNBUFFERED"] = "1"
    env["CENV_VERBOSE"] = "1"
    started = time.time()
    try:
        proc = subprocess.run(
            [sys.executable, "-m", "cenv.build"],
            cwd=str(PAYLOAD),
            env=env,
            text=True,
            capture_output=True,
        )
    except OSError as exc:
        raise RuntimeError(
            f"cenv build could not start (no silent fallback to Python): {exc}"
        ) from exc
    wall = time.time() - started
    for line in (proc.stdout + proc.stderr).strip().splitlines():
        print(line, flush=True)
    if proc.returncode != 0:
        raise RuntimeError(
            "cenv build failed (no silent fallback to Python):\\n"
            + proc.stdout
            + proc.stderr
        )
    lib = Path(proc.stdout.strip().splitlines()[-1])
    if not lib.exists():
        raise RuntimeError(f"cenv build reported success but {lib} is missing")
    cc = cenv_build.default_cc()
    try:
        version = subprocess.run(
            [cc, "--version"], capture_output=True, text=True, check=False
        ).stdout.splitlines()[0]
    except (OSError, IndexError):
        version = cc
    report = {
        "component": JOB.get("cenv"),
        "cc": cc,
        "cc_version": version,
        "cflags": list(cenv_build.CFLAGS) + list(cenv_build.PLATFORM_CFLAGS),
        "lib": str(lib),
        "lib_bytes": lib.stat().st_size,
        "build_seconds": round(wall, 2),
    }
    log(
        f"cenv built in {wall:.1f}s with {version} -> {lib.name} "
        f"({report['lib_bytes']} bytes)"
    )
    return report


