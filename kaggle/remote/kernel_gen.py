def write_kernel(job: dict, slug: str, out_dir: Path | str) -> Path:
    """Writes ``run.py`` + ``kernel-metadata.json`` for one shard; returns the dir."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "run.py").write_text(RUN_TEMPLATE.replace("__JOB__", _job_literal(job)))
    metadata = {
        "id": f"{KAGGLE_USER}/{slug}",
        "title": slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,
        "enable_internet": False,
        "keywords": [],
        "dataset_sources": [DATASET_ID],
        "kernel_sources": [],
        "competition_sources": [COMPETITION_SLUG],
        "model_sources": [],
    }
    (out_dir / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2))
    return out_dir


def _job_literal(job: dict) -> str:
    """The job spec as pretty JSON; the script embeds it verbatim and parses it."""
    return json.dumps(job, indent=4, sort_keys=True)


def default_job(
    *,
    tag: str,
    policy: str,
    scenarios: list[str],
    steps: int,
    sim: str,
    workers: int,
    payload_hash: str,
    params: dict | None = None,
    components: str = "parity",
    start_offset_days: int = 0,
    occupancy_seed: int | None = None,
    oracle: list[str] | None = None,
    oracle_horizon: int | None = None,
    shard: int = 0,
    n_shards: int = 1,
    slug: str = "",
    mount: str = DEFAULT_MOUNT,
    created_utc: str = "",
    keep_trees: bool = False,
    tasks: list[dict] | None = None,
    job_timeout: float = 1800.0,
    cenv: str | None = None,
    fast: bool = False,
    gate: dict | None = None,
) -> dict:
    return {
        "tag": tag,
        "policy": policy,
        "params": params or {},
        "scenarios": list(scenarios),
        "steps": int(steps),
        "sim": sim,
        "workers": int(workers),
        "components": components,
        "start_offset_days": int(start_offset_days),
        "occupancy_seed": occupancy_seed,
        # Opt-in C step: the kernel compiles payload/cenv at start and passes
        # --cenv/--fast to sbx.evalrun. None/False = plain Python.
        "cenv": cenv,
        "fast": bool(fast),
        # Gate mode: plain vs --cenv traces compared by cenv/verify/gate.py.
        "gate": gate,
        # Analysis-only information channel (sbx/evalrun.py --oracle); empty = off.
        "oracle": list(oracle or []),
        "oracle_horizon": oracle_horizon,
        "payload_hash": payload_hash,
        "dataset_dir": DATASET_DIR,
        "mount": mount,
        "shard": int(shard),
        "n_shards": int(n_shards),
        "kernel_slug": slug,
        "created_utc": created_utc,
        # /kaggle/working is snapshotted as the kernel output, and the Kaggle
        # CLI lists it one page at a time (500 files), so the ~1.3 k files of
        # payload + simulator trees would push shard.json off the listing.
        "keep_trees": bool(keep_trees),
        "tasks": tasks,
        "job_timeout": job_timeout,
    }
