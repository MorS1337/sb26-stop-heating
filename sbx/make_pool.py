"""Generates the synthetic building pool and weather strips, reproducibly.

Produces, inside ``sims/shipped/smart_buildings`` (and mirrored into
``sims/corrected/smart_buildings``):

* 24 new buildings, sized like the shipped six: 16 for ``gen_train`` and 8 for
  ``gen_hold``. Geometry comes from the seed alone; envelope materials are
  drawn once for the batch with a Latin hypercube (``utils/materials.py``), the
  same way the shipped buildings were drawn.
* new weather strips ``<station>_g<k>`` -- the *same* recorded 2023 station CSV,
  replayed from a different start date. Gap ``k`` starts one week before that
  station's shipped window ``k+1``, i.e. in the 12-day gap between two shipped
  windows. Why not a start date that no shipped strip uses: the shipped set
  already tiles every Sunday of 2023 with a 06:00 start (six stations offset by
  one week each cover the whole weekly grid, so all 48 usable Sundays are taken);
  the only dates left are in December, where a 30-day episode runs off the end
  of the CSV. ``g`` strips are therefore novel *per station* -- the window is
  never one of that station's eight shipped windows -- which is what a held-out
  weather test needs. Start dates are Sundays 06:00, and the 30-day episode fits
  inside 2023 for every strip (checked below).
* the runnable scenarios for both sets (``config.gin`` + floor plan + zone map),
  generated by the tree's own ``scenario_generator``.
* ``sbx/pools/manifest.json``: every seed, size, measured zone/AHU count, strip
  date and the two scenario lists.

Run from the workspace root::

    python -m sbx.make_pool            # generate everything (idempotent)

Everything is seeded, so a rerun reproduces the same pool byte for byte.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import shutil
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import yaml

WORKSPACE = Path(__file__).resolve().parents[1]
if str(WORKSPACE) not in sys.path:
    sys.path.insert(0, str(WORKSPACE))

from sbx import scenarios as scenario_sets  # noqa: E402
from sbx.simload import sim_root, use_sim  # noqa: E402

# --------------------------------------------------------------------------- #
# pool parameters (changing any of these changes the pool; they are recorded)
# --------------------------------------------------------------------------- #
SEED_START = 5000  # first geometry seed tried; accepted seeds are recorded
SEED_LIMIT = 200  # give up after this many candidate seeds
N_TRAIN_BUILDINGS = 16
N_HOLD_BUILDINGS = 8
MATERIALS_SEED = 20261105
STRIP_GAP_INDEX_TRAIN = (0, 2, 4, 6)  # which gap per station gen_train may use
STRIP_GAP_INDEX_HOLD = (1, 5)  # ... and gen_hold
ZONE_LIMITS = (28, 85)  # V, the shipped six span 30..85
AHU_LIMITS = (3, 9)  # K, the shipped six span 3..9

# Footprint ranges shrunk from run_floor_generator's DEFAULT_RANGES (width
# 400..700, height 300..500) as the README suggests, so the realised zone and
# air-handler counts land inside the shipped range instead of above it.
BUILDING_RANGES = dict(
    building_shape="composite",
    width=(315, 435),
    height=(185, 300),
    num_floors=(2, 4),
    min_room_size=(25, 36),
    room_size_span=(11, 16),
    shape_ratio=(0.28, 0.40),
    composite_coverage=(0.65, 0.85),
    composite_style="architectural",
    num_ahus=(3, 5),
    occupants_per_zone=2,
)

BUILDINGS_SUBDIR = Path("smart_buildings") / "buildings"
WEATHER_SUBDIR = Path("smart_buildings") / "weather"
MANIFEST_PATH = WORKSPACE / "sbx" / "pools" / "manifest.json"

TRAIN_STATIONS = scenario_sets.TRAIN_STATIONS
ALL_STATIONS = scenario_sets.ALL_STATIONS


# --------------------------------------------------------------------------- #
# buildings
# --------------------------------------------------------------------------- #
def _geometry(seed: int, name: str, sg, required_ahus):
    """Builds one config dict and measures it; returns None if unusable."""
    from smart_buildings.smart_control.utils.config_generator import (
        generate_config,
    )

    config = generate_config(name=name, seed=seed, **BUILDING_RANGES)
    scenario_config = sg.scenario_config_from_dict(config)
    try:
        random.seed(seed)
        np.random.seed(seed)
        generator = sg._create_floor_plan_generator(scenario_config.floor_plan)
        generator.generate()
        sg._check_generated_zone_areas(generator, 20, seed)
    except ValueError:
        return None
    zones = generator.get_num_rooms()
    ahus = max(
        scenario_config.ahu.num_ahus,
        required_ahus(zones, scenario_config.ahu.max_zones_per_ahu),
    )
    if not (ZONE_LIMITS[0] <= zones <= ZONE_LIMITS[1]):
        return None
    if not (AHU_LIMITS[0] <= ahus <= AHU_LIMITS[1]):
        return None
    return config, zones, ahus


def _draw_buildings(sg, required_ahus, draw_materials) -> list[dict]:
    """Scans seeds until enough buildings pass the size limits, then names them."""
    accepted: list[dict] = []
    total = N_TRAIN_BUILDINGS + N_HOLD_BUILDINGS
    seed = SEED_START
    while len(accepted) < total and seed < SEED_START + SEED_LIMIT:
        result = _geometry(seed, f"probe_{seed}", sg, required_ahus)
        if result is not None:
            config, zones, ahus = result
            accepted.append({"seed": seed, "config": config, "zones": zones, "ahus": ahus})
        seed += 1
    if len(accepted) < total:
        raise RuntimeError(
            f"only {len(accepted)} of {total} buildings passed the size limits "
            f"in seeds {SEED_START}..{seed}"
        )

    materials = draw_materials(random.Random(MATERIALS_SEED), total)
    for index, entry in enumerate(accepted):
        if index < N_TRAIN_BUILDINGS:
            name = f"building_gen_{index:03d}"
            split = "gen_train"
        else:
            name = f"building_hold_{index - N_TRAIN_BUILDINGS:03d}"
            split = "gen_hold"
        entry["name"] = name
        entry["split"] = split
        entry["config"]["name"] = name
        entry["config"]["materials"] = materials[index]
    return accepted


# --------------------------------------------------------------------------- #
# weather strips
# --------------------------------------------------------------------------- #
def _shipped_windows(station: str) -> list[str]:
    """Start timestamps of the shipped strips of one station, in order."""
    windows = []
    for k in range(1, 9):
        path = WORKSPACE / "sims" / "shipped" / WEATHER_SUBDIR / f"{station}_{k}.yaml"
        if not path.exists():
            continue
        with open(path) as f:
            windows.append(yaml.safe_load(f)["start_timestamp"])
    return sorted(windows)


def _strip_specs() -> list[dict]:
    """Every new strip: one per gap between two shipped windows, per station."""
    import pandas as pd

    specs: list[dict] = []
    for station in ALL_STATIONS:
        windows = _shipped_windows(station)
        reference = (
            WORKSPACE / "sims" / "shipped" / WEATHER_SUBDIR / f"{station}_1.yaml"
        )
        with open(reference) as f:
            base = yaml.safe_load(f)
        for gap in range(len(windows) - 1):
            next_start = pd.Timestamp(windows[gap + 1])
            start = next_start - pd.Timedelta(days=7)
            if start.weekday() != 6:
                raise AssertionError(f"{station} gap {gap}: {start} is not a Sunday")
            end = start + pd.Timedelta(days=30)
            if end.year != 2023:
                raise AssertionError(
                    f"{station} gap {gap}: 30-day episode would end {end}, outside 2023"
                )
            specs.append(
                {
                    "name": f"{station}_g{gap}",
                    "station": station,
                    "gap": gap,
                    "start_timestamp": start.strftime("%Y-%m-%d %H:%M"),
                    "weather_csv": base["weather_csv"],
                    "convection_coefficient": base["convection_coefficient"],
                }
            )
    return specs


# --------------------------------------------------------------------------- #
# generation
# --------------------------------------------------------------------------- #
def _write_yaml(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        yaml.safe_dump(data, f, default_flow_style=False, sort_keys=False)


def _scenario_stats(config_path: Path) -> dict:
    """Zone count from zone_map.npy, AHU count from config.gin."""
    zone_map = np.load(config_path.parent / "zone_map.npy")
    labels = set(np.unique(zone_map).tolist()) - {0.0}
    text = config_path.read_text()
    ahus = len({line.split("/")[0] for line in text.splitlines() if "AirHandler:" in line and line.startswith("ahu_")})
    return {"num_zones": len(labels), "num_ahus": ahus}


def _plan_pairs(buildings: list[dict]) -> dict[str, list[tuple[str, str]]]:
    """Assigns (building, strip) pairs to the sets, deterministically."""
    train = [b for b in buildings if b["split"] == "gen_train"]
    hold = [b for b in buildings if b["split"] == "gen_hold"]

    gen_train: list[tuple[str, str]] = []
    for i, building in enumerate(train):
        for j in range(4):
            station = TRAIN_STATIONS[(4 * i + j) % len(TRAIN_STATIONS)]
            gap = STRIP_GAP_INDEX_TRAIN[(i + j) % len(STRIP_GAP_INDEX_TRAIN)]
            gen_train.append((building["name"], f"{station}_g{gap}"))

    gen_hold: list[tuple[str, str]] = []
    for i, building in enumerate(hold):
        gap_a = STRIP_GAP_INDEX_HOLD[i % len(STRIP_GAP_INDEX_HOLD)]
        gap_b = STRIP_GAP_INDEX_HOLD[(i + 1) % len(STRIP_GAP_INDEX_HOLD)]
        station = TRAIN_STATIONS[i % len(TRAIN_STATIONS)]
        other = TRAIN_STATIONS[(i + 2) % len(TRAIN_STATIONS)]
        gen_hold.append((building["name"], f"{scenario_sets.HOLD_STATION}_g{gap_a}"))
        gen_hold.append((building["name"], f"{scenario_sets.HOLD_STATION}_g{gap_b}"))
        gen_hold.append((building["name"], f"{station}_g{gap_a}"))
        gen_hold.append((building["name"], f"{other}_g{gap_b}"))

    pairs = {"gen_train": gen_train, "gen_hold": gen_hold}
    ext_hold = _plan_ext_hold(buildings)
    if ext_hold:
        pairs["ext_hold"] = ext_hold
    return pairs


def _external_strips() -> dict[str, list[str]]:
    """Strip names per *external* climate station, from the shipped tree.

    External presets are contributed by ``sbx/weather_ext.py`` (17 unseen
    stations, 3 strips each). They are recognised by elimination: anything in
    ``weather/`` that is neither a shipped station strip nor one of this
    module's ``<station>_g<k>`` gaps.
    """
    known_stations = set(ALL_STATIONS)
    groups: dict[str, list[str]] = {}
    weather_dir = sim_root("shipped") / WEATHER_SUBDIR
    for path in sorted(weather_dir.glob("*.yaml")):
        name = path.stem
        station = name.rsplit("_", 1)[0]
        if station in known_stations:
            continue
        groups.setdefault(station, []).append(name)
    return groups


def _plan_ext_hold(buildings: list[dict]) -> list[tuple[str, str]]:
    """One scenario per external station, round-robin over 8 hold + 2 shipped."""
    groups = _external_strips()
    if not groups:
        print(
            "[make_pool] no external weather presets installed in sims/shipped "
            "(sbx/weather_ext.py); skipping the ext_hold set",
            flush=True,
        )
        return []

    hold = [b["name"] for b in buildings if b["split"] == "gen_hold"]
    roster = hold + ["building_train_1", "building_train_8"]
    pairs: list[tuple[str, str]] = []
    for i, station in enumerate(sorted(groups)):
        strips = sorted(groups[station])
        pairs.append((roster[i % len(roster)], strips[i % len(strips)]))
    return pairs


def _mirror(source_root: Path, dest_root: Path, buildings: list[dict], strips: list[dict], pairs: dict) -> list[str]:
    """Copies the generated YAMLs and scenario dirs into the other tree."""
    copied: list[str] = []
    for building in buildings:
        rel = BUILDINGS_SUBDIR / f"{building['name']}.yaml"
        dest = dest_root / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source_root / rel, dest)
        copied.append(str(rel))
    strip_names = {s["name"] for s in strips}
    # External presets used by ext_hold are not generated here but the configs
    # refer to them, so carry them across too (same bytes on both sides).
    strip_names |= {w for ps in pairs.values() for _, w in ps if w not in strip_names
                    and (source_root / WEATHER_SUBDIR / f"{w}.yaml").exists()}
    for name in sorted(strip_names):
        rel = WEATHER_SUBDIR / f"{name}.yaml"
        dest = dest_root / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source_root / rel, dest)
        copied.append(str(rel))
    for scenarios in pairs.values():
        for building_name, strip_name in scenarios:
            rel = scenario_sets.SCENARIOS_SUBDIR / building_name / strip_name
            shutil.copytree(source_root / rel, dest_root / rel, dirs_exist_ok=True)
            copied.append(str(rel))
    return copied


def make_pool(force: bool = False) -> dict:
    """Generates the pool into ``sims/shipped``, mirrors it, writes the manifest."""
    use_sim("shipped")
    from smart_buildings.smart_control.utils import scenario_generator as sg
    from smart_buildings.smart_control.utils.floor_generator import required_ahus
    from smart_buildings.smart_control.utils.materials import draw_materials

    shipped_root = sim_root("shipped")
    started = time.time()

    print("[make_pool] drawing buildings ...", flush=True)
    buildings = _draw_buildings(sg, required_ahus, draw_materials)
    for building in buildings:
        _write_yaml(
            shipped_root / BUILDINGS_SUBDIR / f"{building['name']}.yaml",
            building["config"],
        )

    print("[make_pool] writing weather strips ...", flush=True)
    strips = _strip_specs()
    for strip in strips:
        _write_yaml(
            shipped_root / WEATHER_SUBDIR / f"{strip['name']}.yaml",
            {
                "name": strip["name"],
                "weather_csv": strip["weather_csv"],
                "convection_coefficient": strip["convection_coefficient"],
                "start_timestamp": strip["start_timestamp"],
                "note": (
                    f"{strip['station']} recorded data replayed from a start date in "
                    f"gap {strip['gap']} between two shipped windows; generated by "
                    "sbx/make_pool.py"
                ),
            },
        )

    pairs = _plan_pairs(buildings)
    print(
        f"[make_pool] generating {sum(len(v) for v in pairs.values())} scenarios ...",
        flush=True,
    )
    scenario_info: dict[str, dict] = {}
    for set_name, set_pairs in pairs.items():
        for building_name, strip_name in set_pairs:
            output_dir = (
                shipped_root
                / scenario_sets.SCENARIOS_SUBDIR
                / building_name
                / strip_name
            )
            config_path = output_dir / "config.gin"
            if force or not config_path.exists():
                config = sg.load_scenario_from_parts(
                    str(shipped_root / BUILDINGS_SUBDIR / f"{building_name}.yaml"),
                    str(shipped_root / WEATHER_SUBDIR / f"{strip_name}.yaml"),
                    output_base_dir=str(scenario_sets.SCENARIOS_SUBDIR),
                )
                sg.generate_scenario_from_config(config)
            key = f"{building_name}/{strip_name}"
            scenario_info[key] = {
                "set": set_name,
                **_scenario_stats(config_path),
            }
            scenario_info[key]["config_sha"] = hashlib.sha256(
                config_path.read_bytes()
            ).hexdigest()

    print("[make_pool] mirroring into sims/corrected ...", flush=True)
    mirrored = _mirror(
        shipped_root, sim_root("corrected"), buildings, strips, pairs
    )

    manifest = {
        "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "generator": {
            "module": "sbx.make_pool",
            "sim_generated_in": "shipped",
            "seed_start": SEED_START,
            "seed_limit": SEED_LIMIT,
            "materials_seed": MATERIALS_SEED,
            "building_ranges": BUILDING_RANGES,
            "zone_limits": ZONE_LIMITS,
            "ahu_limits": AHU_LIMITS,
            "strip_gap_index_train": STRIP_GAP_INDEX_TRAIN,
            "strip_gap_index_hold": STRIP_GAP_INDEX_HOLD,
            "strip_rule": (
                "gap k starts one week before the station's shipped window k+1, "
                "i.e. inside the 12-day gap between two shipped windows"
            ),
        },
        "buildings": [
            {
                "name": b["name"],
                "split": b["split"],
                "seed": b["seed"],
                "num_zones": b["zones"],
                "num_ahus": b["ahus"],
                "width": b["config"]["floor_plan"]["width"],
                "height": b["config"]["floor_plan"]["height"],
                "num_floors": b["config"]["floor_plan"]["num_floors"],
                "min_room_size": b["config"]["floor_plan"]["min_room_size"],
                "max_room_size": b["config"]["floor_plan"]["max_room_size"],
                "materials": b["config"]["materials"],
            }
            for b in buildings
        ],
        "strips": [
            {
                "name": s["name"],
                "station": s["station"],
                "gap": s["gap"],
                "start_timestamp": s["start_timestamp"],
                "weather_csv": s["weather_csv"],
                "used_by": [n for n, ps in pairs.items() if any(p[1] == s["name"] for p in ps)],
            }
            for s in strips
        ],
        "sets": {
            name: [f"{b}/{w}" for b, w in set_pairs]
            for name, set_pairs in pairs.items()
        },
        "scenarios": scenario_info,
        "mirrored_files": len(mirrored),
        "wall_seconds": None,
    }

    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    manifest["wall_seconds"] = round(time.time() - started, 1)
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2))
    print(
        f"[make_pool] done in {manifest['wall_seconds']}s: "
        f"{len(buildings)} buildings, {len(strips)} strips, "
        f"{len(manifest['sets']['gen_train'])} gen_train + "
        f"{len(manifest['sets']['gen_hold'])} gen_hold scenarios -> {MANIFEST_PATH}",
        flush=True,
    )
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--force", action="store_true", help="regenerate scenario dirs that exist"
    )
    args = parser.parse_args(argv)
    manifest = make_pool(force=args.force)
    zones = [b["num_zones"] for b in manifest["buildings"]]
    ahus = [b["num_ahus"] for b in manifest["buildings"]]
    print(
        f"[make_pool] zones {min(zones)}..{max(zones)}, ahus {min(ahus)}..{max(ahus)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
